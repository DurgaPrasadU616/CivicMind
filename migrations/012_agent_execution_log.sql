-- Phase 1 — Creates the agent_execution_log table for structured, append-only
-- audit logging of every step taken by any autonomous agent.
--
-- Design decisions:
--   • APPEND-ONLY by application contract (no UPDATE/DELETE paths in codebase).
--   • run_id groups all steps belonging to a single agent invocation.
--   • cluster_id and complaint_id are nullable — some agents act system-wide.
--   • input_data / output_data stored as JSONB for schema flexibility.
--   • model_used / tokens_used allow cost and performance tracking.
--   • status uses a constrained CHECK so invalid values fail at the DB layer.
--
-- ✅ Additive only — no existing table is altered.
-- ✅ Idempotent — safe to run multiple times.
-- ✅ Reversible — see DOWN section.
-- =============================================================================

-- ── 1. Create the table ──────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS agent_execution_log (
    id              SERIAL PRIMARY KEY,

    -- Which agent type generated this step
    agent_type      VARCHAR(50) NOT NULL
                        CHECK (agent_type IN (
                            'investigation',
                            'routing',
                            'planning',
                            'monitoring',
                            'hybrid_clustering',
                            'media_analysis',
                            'system'
                        )),

    -- Optional foreign keys — nullable for system-wide agent runs
    cluster_id      INT REFERENCES cluster(id)   ON DELETE SET NULL,
    complaint_id    INT REFERENCES complaint(id)  ON DELETE SET NULL,

    -- Groups all steps of a single agent invocation
    -- Generated by the caller (crypto.randomUUID() in Node)
    run_id          UUID NOT NULL,

    -- Ordered position within this run (0-based)
    step_index      INT NOT NULL DEFAULT 0,

    -- Human-readable step label (e.g. 'fetch_cluster', 'embed_text', 'generate_plan')
    step_name       VARCHAR(100) NOT NULL,

    -- Serialised inputs and outputs for this step
    input_data      JSONB,
    output_data     JSONB,

    -- AI model details (optional — set when an LLM was called)
    model_used      VARCHAR(80),
    tokens_used     INT,
    duration_ms     INT,                          -- wall-clock time for this step

    -- Step lifecycle
    status          VARCHAR(20) NOT NULL
                        CHECK (status IN ('running', 'success', 'failed', 'skipped')),
    error_message   TEXT,                         -- populated when status = 'failed'

    -- Who or what triggered the agent run
    triggered_by    VARCHAR(50) NOT NULL DEFAULT 'system',
                        -- e.g. 'system' | 'cron' | 'user:<user_id>' | 'api'

    triggered_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── 2. Indexes ───────────────────────────────────────────────────────────────

-- Primary access pattern: "show me all steps for this run, in order"
CREATE INDEX IF NOT EXISTS idx_agent_log_run_id
    ON agent_execution_log (run_id, step_index ASC);

-- Dashboard query: "recent agent activity for a given cluster"
CREATE INDEX IF NOT EXISTS idx_agent_log_cluster
    ON agent_execution_log (cluster_id, triggered_at DESC)
    WHERE cluster_id IS NOT NULL;

-- Ops/monitoring: "all recent failures across any agent type"
CREATE INDEX IF NOT EXISTS idx_agent_log_status_at
    ON agent_execution_log (status, triggered_at DESC);

-- Filter by agent type (e.g. show only 'investigation' runs)
CREATE INDEX IF NOT EXISTS idx_agent_log_agent_type
    ON agent_execution_log (agent_type, triggered_at DESC);

